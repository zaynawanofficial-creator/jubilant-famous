"""Writes wp-content/plugins/iamfamous-core/data/group-content-ifm-2.php from tools/package_copy.py.
Run: python3 tools/build_package_copy.py"""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from package_copy import GROUPS

def q(s):
    return "'" + str(s).replace('\\', '\\\\').replace("'", "\\'") + "'"

def lines(items):
    return q('\n'.join(items)).replace('\n', "' . \"\\n\" . '")

out = ["<?php", "/**", " * Generated by tools/build_package_copy.py from tools/package_copy.py. Do not edit by hand.",
       " * IamFamous wording for every package group outside the three round 1 services; merged by IFM_Importer::content().",
       " *", " * @package IamFamousCore", " */", "", "defined( 'ABSPATH' ) || exit;", "", "return array("]
for key, g in GROUPS.items():
    out.append(f"\t{q(key)} => array(")
    out.append(f"\t\t'intro'        => {q(g['intro'])},")
    if 'brief' in g:
        out.append(f"\t\t'brief'        => {q(g['brief'])},")
    if 'D' in g:
        out.append(f"\t\t'deliverables' => {lines(g['D'])},")
    out.append(f"\t\t'exclusions'   => {lines(g['X'])},")
    out.append(f"\t\t'requirements' => {lines(g['R'])},")
    if 'ideal' in g:
        out.append("\t\t'ideal_for'    => array( " + ', '.join(f"{k} => {q(v)}" for k, v in g['ideal'].items()) + " ),")
    if 'sku' in g:
        out.append("\t\t'by_sku'       => array(")
        for n, (ideal, deliv) in g['sku'].items():
            parts = [f"'ideal_for' => {q(ideal)}"]
            if deliv:
                parts.append(f"'deliverables' => {lines(deliv)}")
            if g.get('featured') == n:
                parts.append("'featured' => true")
            out.append(f"\t\t\t{q(g['prefix'] + '-' + str(n))} => array( " + ', '.join(parts) + " ),")
        out.append("\t\t),")
    out.append("\t),")
out += [");", ""]
path = os.path.join(HERE, '..', 'wp-content', 'plugins', 'iamfamous-core', 'data', 'group-content-ifm-2.php')
open(path, 'w').write('\n'.join(out))
print(len(GROUPS), 'groups written')
